// Windows Terminal themes built from a flavour's resolved colour map.
//
// Pure ESM, no Node or DOM APIs, so the same code drives both
// `scripts/build-themes.mjs` and the app's _Terminal theme_ download button —
// the same split as `scripts/theme.mjs` for the browser themes.
//
// Windows Terminal's sixteen ANSI slots are semantic ("the palette's red"),
// not "whatever this palette happens to call red", so the mapping below follows
// Catppuccin's own Windows Terminal port (github.com/catppuccin/windows-terminal)
// slot for slot. A Catppuccin flavour therefore reproduces upstream's scheme
// exactly, and Gruvbox/Everforest/Kanagawa get the same treatment through their
// Catppuccin-style aliases: `rosewater` is their warm accent, `pink` their
// magenta and `aqua`/`teal` their cyan.
//
// The accent selector deliberately plays no part here: all sixteen slots
// already belong to the palette itself, exactly as they do upstream.
//
// Both maps list the slots in the order upstream's files do, so the generated
// scheme can be diffed against them directly.

// Dark schemes: the greys step outwards from the background (surface1 →
// brightBlack → white → brightWhite), so the *bright* half of black/white is
// the lighter (or, on a dark theme, the more prominent) one.
const DARK_SCHEME = {
	cursorColor: 'rosewater',
	selectionBackground: 'surface2',
	background: 'base',
	foreground: 'text',
	black: 'surface1',
	red: 'red',
	green: 'green',
	yellow: 'yellow',
	blue: 'blue',
	purple: 'pink',
	cyan: 'aqua',
	white: 'subtext1',
	brightBlack: 'surface2',
	brightRed: 'red',
	brightGreen: 'green',
	brightYellow: 'yellow',
	brightBlue: 'blue',
	brightPurple: 'pink',
	brightCyan: 'aqua',
	brightWhite: 'subtext0',
};

// Light schemes: the same slots, but black starts at the body text and the
// white pair climbs the surface ramp instead (upstream's Latte does exactly
// this), so the bright half stays the lighter one.
const LIGHT_SCHEME = {
	cursorColor: 'rosewater',
	selectionBackground: 'surface2',
	background: 'base',
	foreground: 'text',
	black: 'subtext1',
	red: 'red',
	green: 'green',
	yellow: 'yellow',
	blue: 'blue',
	purple: 'pink',
	cyan: 'aqua',
	white: 'surface2',
	brightBlack: 'surface2',
	brightRed: 'red',
	brightGreen: 'green',
	brightYellow: 'yellow',
	brightBlue: 'blue',
	brightPurple: 'pink',
	brightCyan: 'aqua',
	brightWhite: 'surface1',
};

/**
 * A Windows Terminal colour scheme (one entry of `settings.json` > `schemes`).
 *
 * @param {{ name: string, colors: Record<string, string>, dark?: boolean }} options
 *   `colors` maps palette tokens (`base`, `surface1`, `pink`, …) to hex strings.
 */
export function windowsTerminalScheme({ name, colors, dark = true }) {
	const table = dark ? DARK_SCHEME : LIGHT_SCHEME;
	const scheme = { name };
	for (const [slot, token] of Object.entries(table)) {
		scheme[slot] = colors[token];
	}
	return scheme;
}

/**
 * The matching window theme (one entry of `settings.json` > `themes`), which
 * colours the tab row and title bar. Windows Terminal wants 8-digit ARGB here.
 *
 * @param {{ name: string, colors: Record<string, string>, dark?: boolean }} options
 */
export function windowsTerminalWindowTheme({ name, colors, dark = true }) {
	return {
		name,
		tab: {
			background: `${colors.base}FF`,
			showCloseButton: 'always',
			unfocusedBackground: null,
		},
		tabRow: {
			background: `${colors.mantle}FF`,
			unfocusedBackground: `${colors.crust}FF`,
		},
		window: { applicationTheme: dark ? 'dark' : 'light' },
	};
}

/**
 * The two `settings.json` keys a flavour contributes, ready to merge by hand —
 * no actions, profiles or keybindings, since those are personal.
 *
 * @param {{ name: string, colors: Record<string, string>, dark?: boolean }} options
 */
export function windowsTerminalSnippet({ name, colors, dark = true }) {
	return {
		schemes: [windowsTerminalScheme({ name, colors, dark })],
		themes: [windowsTerminalWindowTheme({ name, colors, dark })],
	};
}

/** How to paste a snippet into `settings.json`, shipped with the themes. */
export function windowsTerminalReadme() {
	return `# Windows Terminal themes

Generated by \`node scripts/build-themes.mjs\` — do not edit by hand.

One file per palette variant, named exactly like the browser theme built from
the same colours. Each file holds only the two \`settings.json\` keys a terminal
theme needs:

    {
      "schemes": [ ... the ANSI colour scheme ... ],
      "themes":  [ ... the matching tab row and title bar colours ... ]
    }

Everything else in \`settings.json\` is personal (actions, profiles,
keybindings), which is why it is not included.

## Installing

Open Settings (Ctrl+,) and click "Open JSON file", or run \`settings.json\` from
the command palette, then merge the file in by hand:

1. Copy the object from \`schemes\` into the top-level \`"schemes"\` array.
2. Copy the object from \`themes\` into the top-level \`"themes"\` array.
3. Point a profile at the scheme with \`"colorScheme": "<name>"\`, and the whole
   window at the theme with \`"theme": "<name>"\`. Both use the same name, which
   is this file's name without \`.json\`.

Windows Terminal 1.22 and later can also pair a light and a dark theme, so a
profile follows the system setting:

    "theme": { "light": "<a light file's name>", "dark": "<a dark file's name>" }

The sixteen ANSI colours are fixed per palette (the scheme's own red, green,
yellow, blue, magenta, cyan, black and white), exactly as Catppuccin's own
Windows Terminal port defines them — the accent picker shapes the userstyles and
the browser themes, not the terminal.
`;
}
