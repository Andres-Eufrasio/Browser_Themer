// Generates a browser theme (Chrome/Edge/Brave + Firefox) for every flavour:
// 3 palettes x 2 modes x 3 contrast levels = 18 themes.
//
// Run with `node scripts/build-themes.mjs` (or `pnpm themes`). Output lands in
// `themes/`, which is generated and gitignored.
//
// Colours come from the same `palette-data.mjs` that feeds the userstyles, so a
// theme always matches the styles it ships with.

import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import {
	CONTRASTS,
	FLAVORS,
	PALETTE_LABELS,
	PALETTES,
} from './palette-data.mjs';
import {
	SIGNATURE_ACCENT,
	chromeThemeManifest,
	firefoxThemeManifest,
	formatManifest,
	themeReadme,
} from './theme.mjs';
import { createZip } from './zip.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(here, '..', 'themes');

const titleCase = (value) => value[0].toUpperCase() + value.slice(1);

function indexReadme(themes) {
	return `# Browser themes

Generated by \`node scripts/build-themes.mjs\` — do not edit by hand.

One theme per flavour (${themes.length} total), built from the same palette
definitions as the userstyles, so the browser chrome and the themed sites agree.
Each theme uses its palette's signature accent (the *Accent* column); the app's
*Browser theme* button builds the same theme with any of the 21 accents instead.

| Theme | Accent |
| --- | --- |
${themes.map(({ name, accent }) => `| [${name}](./${name}/readme.txt) | \`${accent}\` |`).join('\n')}

## Installing

Every theme folder holds both manifests and its own \`readme.txt\` with the
same steps:

* **Chrome / Edge / Brave** — the folder itself is the theme:
  \`chrome://extensions\` > Developer mode > *Load unpacked* > pick the folder.
  Chrome blocks sideloaded \`.crx\` files, so \`*-chrome.zip\` exists only to move
  the folder between machines; extract it and load the extracted folder.
* **Firefox** — \`*-firefox.xpi\` is unsigned, so it installs only after
  Firefox has verified a signature: load it temporarily via
  \`about:debugging#/runtime/this-firefox\`, or sign it for free on
  addons.mozilla.org for a permanent install.

Themes only recolour browser UI (tabs, toolbar, omnibox, menus, New Tab page).
They change no page content.
`;
}

rmSync(outDir, { recursive: true, force: true });

const written = [];
for (const { palette, mode } of FLAVORS) {
	const accent = SIGNATURE_ACCENT[palette];
	const dark = mode === 'dark';

	for (const contrast of CONTRASTS) {
		const colors = PALETTES[palette][mode][contrast];
		const name = `${PALETTE_LABELS[palette]} ${titleCase(mode)} ${titleCase(contrast)}`;
		const dir = path.join(outDir, name);

		const chrome = formatManifest(
			chromeThemeManifest({ name, colors, accent }),
		);
		const firefox = formatManifest(
			firefoxThemeManifest({ name, colors, accent, dark }),
		);

		mkdirSync(path.join(dir, 'firefox'), { recursive: true });
		writeFileSync(path.join(dir, 'manifest.json'), chrome);
		writeFileSync(path.join(dir, 'firefox', 'manifest.json'), firefox);
		writeFileSync(path.join(dir, 'readme.txt'), themeReadme(name));
		// Chrome archives the folder so extracting one yields a clean theme
		// directory; Firefox needs manifest.json at the archive root.
		writeFileSync(
			path.join(dir, `${name}-chrome.zip`),
			createZip([{ path: `${name}/manifest.json`, data: chrome }]),
		);
		writeFileSync(
			path.join(dir, `${name}-firefox.xpi`),
			createZip([{ path: 'manifest.json', data: firefox }]),
		);

		written.push({ name, accent });
	}
}

writeFileSync(path.join(outDir, 'README.md'), indexReadme(written));

console.log(`wrote ${written.length} themes to themes/`);
