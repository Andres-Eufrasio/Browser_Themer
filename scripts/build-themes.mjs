// Generates, for every palette variant, a browser theme (Chrome/Edge/Brave +
// Firefox) and a Windows Terminal theme. Gruvbox, Everforest and Kanagawa each
// contribute one variant per mode x contrast; every other palette ships no
// contrast levels, so each fixed-scheme variant (Catppuccin's flavours and the
// rest) contributes a single theme.
//
// Run with `node scripts/build-themes.mjs` (or `pnpm themes`). Output lands in
// `themes/`, which is generated and gitignored.
//
// Colours come from the same `palette-data.mjs` that feeds the userstyles, so a
// theme always matches the styles it ships with.

import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import {
	CONTRASTS,
	PALETTES,
	PALETTE_LABELS,
	PALETTE_SCHEMES,
} from './palette-data.mjs';
import {
	SIGNATURE_ACCENT,
	chromeThemeManifest,
	firefoxThemeManifest,
	formatManifest,
	themeReadme,
} from './theme.mjs';
import { createZip } from './zip.mjs';
import { windowsTerminalReadme, windowsTerminalSnippet } from './terminal.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(here, '..', 'themes');
// Terminal themes are one JSON fragment per variant, not an installable folder,
// so they live beside the theme folders rather than inside one.
const terminalDir = path.join(outDir, 'windows-terminal');

const titleCase = (value) => value[0].toUpperCase() + value.slice(1);

function indexReadme(themes) {
	return `# Browser themes

Generated by \`node scripts/build-themes.mjs\` — do not edit by hand.

One theme per palette variant (${themes.length} total), built from the same
palette definitions as the userstyles, so the browser chrome and the themed
sites agree. Palettes that define no contrast levels — Catppuccin's flavours and
the other fixed-scheme variants — get a single theme each, named after the
variant itself.

Each theme uses its palette's signature accent (the *Accent* column); the app's
*Browser theme* button builds the same theme with any of the 32 accents instead.

| Theme | Accent |
| --- | --- |
${themes.map(({ name, accent }) => `| [${name}](./${name}/readme.txt) | \`${accent}\` |`).join('\n')}

## Installing

Every theme folder holds both manifests and its own \`readme.txt\` with the
same steps:

* **Chrome / Edge / Brave** — the folder itself is the theme:
  \`chrome://extensions\` > Developer mode > *Load unpacked* > pick the folder.
  Chrome blocks sideloaded \`.crx\` files, so \`*-chrome.zip\` exists only to move
  the folder between machines; extract it and load the extracted folder.
* **Firefox** — \`*-firefox.xpi\` is unsigned, so it installs only after
  Firefox has verified a signature: load it temporarily via
  \`about:debugging#/runtime/this-firefox\`, or sign it for free on
  addons.mozilla.org for a permanent install.

Themes only recolour browser UI (tabs, toolbar, omnibox, menus, New Tab page).
They change no page content.

## Windows Terminal

\`windows-terminal/\` holds the same ${themes.length} variants as \`settings.json\`
fragments: only the \`schemes\` and \`themes\` entries, ready to merge by hand.
Nothing personal (actions, profiles, keybindings) is included. See
\`windows-terminal/README.md\` for the three steps.
`;
}

rmSync(outDir, { recursive: true, force: true });
mkdirSync(terminalDir, { recursive: true });

const written = [];
for (const [palette, modes] of Object.entries(PALETTES)) {
	const label = PALETTE_LABELS[palette];
	const accent = SIGNATURE_ACCENT[palette];
	const scheme = PALETTE_SCHEMES[palette];
	// A palette whose flavour already is the variant (Catppuccin) is emitted
	// once, under its own name; a palette with a background ramp gets one theme
	// per mode x contrast combination.
	const uniform = scheme.dark === scheme.light;

	const variants = [];
	for (const mode of ['dark', 'light']) {
		for (const contrast of CONTRASTS) {
			const colors = modes[mode][contrast];
			const signature = JSON.stringify(colors);
			if (variants.some((variant) => variant.signature === signature)) {
				continue;
			}
			variants.push({
				colors,
				signature,
				// The palette's own light/dark side, not the slot it came from.
				dark: scheme[mode] === 'dark',
				name: uniform
					? label
					: `${label} ${titleCase(mode)} ${titleCase(contrast)}`,
			});
		}
	}

	for (const { colors, dark, name } of variants) {
		const dir = path.join(outDir, name);

		const chrome = formatManifest(
			chromeThemeManifest({ name, colors, accent }),
		);
		const firefox = formatManifest(
			firefoxThemeManifest({ name, colors, accent, dark }),
		);

		mkdirSync(path.join(dir, 'firefox'), { recursive: true });
		writeFileSync(path.join(dir, 'manifest.json'), chrome);
		writeFileSync(path.join(dir, 'firefox', 'manifest.json'), firefox);
		writeFileSync(path.join(dir, 'readme.txt'), themeReadme(name));
		// Chrome archives the folder so extracting one yields a clean theme
		// directory; Firefox needs manifest.json at the archive root.
		writeFileSync(
			path.join(dir, `${name}-chrome.zip`),
			createZip([{ path: `${name}/manifest.json`, data: chrome }]),
		);
		writeFileSync(
			path.join(dir, `${name}-firefox.xpi`),
			createZip([{ path: 'manifest.json', data: firefox }]),
		);

		// The same colours as a Windows Terminal fragment. Windows Terminal
		// names its colour schemes, so the scheme and the window theme share the
		// variant's name (and the browser theme's), which is what `colorScheme`
		// and `theme` in a profile refer to.
		writeFileSync(
			path.join(terminalDir, `${name}.json`),
			formatManifest(windowsTerminalSnippet({ name, colors, dark })),
		);

		written.push({ name, accent });
	}
}

writeFileSync(path.join(terminalDir, 'README.md'), windowsTerminalReadme());
writeFileSync(path.join(outDir, 'README.md'), indexReadme(written));

console.log(
	`wrote ${written.length} browser themes and Windows Terminal themes to themes/`,
);
